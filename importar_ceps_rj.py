def importar_ceps(ceps_texto):
    """Importa os CEPs do texto para a planilha Cidaten"""
    
    # Carregar planilha existente
    try:
        df = pd.read_excel('Cidaten_2026.xlsx', sheet_name='Cidaten', header=1)
        print("📂 Planilha Cidaten carregada.")
    except:
        df = pd.DataFrame(columns=['UF', 'Localidade', 'Cep', 'Prazo Rodo', 'Tipo Tarifa', 'Frap (Fob)', '% Seguro'])
        print("📄 Nova planilha Cidaten criada.")
    
    # Processar cada linha
    novas_linhas = []
    linhas = ceps_texto.strip().split('\n')
    
    for linha in linhas:
        linha = linha.strip()
        if not linha or linha.startswith('#'):
            continue
        
        # Parse: "CIDADE: INICIO a FIM - TIPO"
        match = re.match(r'(.+?):\s*(.+?)\s*a\s*(.+?)\s*-\s*(.+)', linha)
        if not match:
            print(f"⚠️ Linha ignorada: {linha[:50]}...")
            continue
        
        cidade = match.group(1).strip().upper()
        cep_ini = match.group(2).strip()
        cep_fim = match.group(3).strip()
        tipo = match.group(4).strip()
        
        # Determinar prazo
        if "Capital 1" in tipo:
            prazo = 3
        elif "Capital 2" in tipo:
            prazo = 4
        elif "Capital 3" in tipo:
            prazo = 5
        elif "Interior 1" in tipo:
            prazo = 5
        elif "Interior 2" in tipo:
            prazo = 6
        elif "Interior 3" in tipo:
            prazo = 7
        else:
            prazo = 5
        
        # Formatar CEP
        if cep_ini == cep_fim:
            cep_str = cep_ini
        else:
            cep_str = f"{cep_ini} a {cep_fim}"
        
        # Verificar se já existe (evitar duplicatas)
        existe = False
        for _, row in df.iterrows():
            if row['Localidade'] == cidade and row['Cep'] == cep_str:
                existe = True
                break
        
        if not existe:
            novas_linhas.append({
                'UF': 'RJ',
                'Localidade': cidade,
                'Cep': cep_str,
                'Prazo Rodo': prazo,
                'Tipo Tarifa': tipo,
                'Frap (Fob)': 'Nao',
                '% Seguro': 0.0066
            })
    
    if novas_linhas:
        df_novo = pd.DataFrame(novas_linhas)
        df = pd.concat([df, df_novo], ignore_index=True)
        df.to_excel('Cidaten_2026.xlsx', sheet_name='Cidaten', index=False, header=True)
        print(f"\n✅ {len(novas_linhas)} CEPs do RJ adicionados com sucesso!")
        print(f"📊 Total de CEPs na planilha: {len(df)}")
    else:
        print("\n⚠️ Nenhum CEP novo foi adicionado (todos já existem).")

