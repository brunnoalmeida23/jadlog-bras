def _carregar_tabelas() -> dict:
    tabelas: dict = {}

    for chave, texto in DADOS_TABELAS.items():
        tabela_uf: dict = {}

        for linha in texto.strip().splitlines():
            partes = [item.strip() for item in linha.split(";")]

            if len(partes) != 7:
                raise RuntimeError(
                    f"Linha inválida na tabela {chave}: {linha}"
                )

            uf = partes[0].upper()

            tabela_uf[uf] = {
                "1": Decimal(partes[1]),
                "5": Decimal(partes[2]),
                "10": Decimal(partes[3]),
                "20": Decimal(partes[4]),
                "30": Decimal(partes[5]),
                "adicional": Decimal(partes[6]),
            }

        tabelas[chave] = tabela_uf

    return tabelas


TABELAS = _carregar_tabelas()


def _arredondar(valor: Decimal) -> Decimal:
    return valor.quantize(
        Decimal("0.01"),
        rounding=ROUND_HALF_UP,
    )


def _normalizar_modalidade(modalidade: str) -> str:
    texto = str(modalidade or "").strip().upper()

    if texto in {".COM", "COM"}:
        return "COM"

    if texto in {"PACKAGE", "PACK", "PACLAGE"}:
        return "PACKAGE"

    raise ErroComissao(
        f"Modalidade não reconhecida: {modalidade}"
    )


def _normalizar_tipo(tipo_tarifa: str) -> str:
    texto = (
        str(tipo_tarifa or "")
        .strip()
        .upper()
        .replace("_", " ")
    )

    texto = " ".join(texto.split())

    if texto in {
        "CAPITAL 1",
        "CAPITAL 2",
        "CAPITAL 3",
        "INTERIOR 1",
        "INTERIOR 2",
        "INTERIOR 3",
    }:
        return texto

    raise ErroComissao(
        f"Tipo tarifário não reconhecido: {tipo_tarifa}"
    )


def _calcular_interior(peso: Decimal) -> Decimal:
    for limite, valor in INTERIOR_FAIXAS:
        if peso <= limite:
            return valor

    raise ErroComissao(
        "Peso acima de 100 kg sem comissão de Interior definida."
    )


def _calcular_capital(
    modalidade: str,
    tipo_tarifa: str,
    uf: str,
    peso: Decimal,
) -> Decimal:
    chave = (modalidade, tipo_tarifa)
    tabela = TABELAS.get(chave)

    if tabela is None:
        raise ErroComissao(
            f"Tabela não encontrada: {modalidade} / {tipo_tarifa}"
        )

    dados_uf = tabela.get(str(uf or "").strip().upper())

    if dados_uf is None:
        raise ErroComissao(
            f"UF não encontrada na tabela: {uf}"
        )

    if peso <= Decimal("1"):
        return dados_uf["1"]

    if peso <= Decimal("5"):
        return dados_uf["5"]

    if peso <= Decimal("10"):
        return dados_uf["10"]

    if peso <= Decimal("20"):
        return dados_uf["20"]

    if peso <= Decimal("30"):
        return dados_uf["30"]

    excedente = peso - Decimal("30")

    return (
        dados_uf["30"]
        + excedente * dados_uf["adicional"]
    )


def calcular_comissao(
    modalidade: str,
    tipo_tarifa: str,
    uf: str,
    peso: float,
) -> float:
    modalidade_normalizada = _normalizar_modalidade(
        modalidade
    )

    tipo_normalizado = _normalizar_tipo(tipo_tarifa)

    peso_decimal = Decimal(str(peso))

    if peso_decimal <= 0:
        raise ErroComissao(
            "O peso deve ser maior que zero."
        )

    if tipo_normalizado.startswith("INTERIOR"):
        comissao = _calcular_interior(peso_decimal)
    else:
        comissao = _calcular_capital(
            modalidade=modalidade_normalizada,
            tipo_tarifa=tipo_normalizado,
            uf=uf,
            peso=peso_decimal,
        )

    return float(_arredondar(comissao))


def aplicar_comissao(
    valor_api: float,
    modalidade: str,
    tipo_tarifa: str,
    uf: str,
    peso: float,
) -> dict:
    comissao = calcular_comissao(
        modalidade=modalidade,
        tipo_tarifa=tipo_tarifa,
        uf=uf,
        peso=peso,
    )

    valor_final = _arredondar(
        Decimal(str(valor_api))
        + Decimal(str(comissao))
    )

    return {
        "valor_api": round(float(valor_api), 2),
        "comissao": round(comissao, 2),
        "valor_final": float(valor_final),
        "modalidade": _normalizar_modalidade(modalidade),
        "tipo_tarifa": _normalizar_tipo(tipo_tarifa),
        "uf": str(uf or "").strip().upper(),
    }